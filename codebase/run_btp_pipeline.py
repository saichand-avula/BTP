#!/usr/bin/env python3
"""Run the complete reproducible analysis and write machine-readable outputs."""
from pathlib import Path
import math
import re
import sys
import pandas as pd


BASE = Path(__file__).parent
MODELS = BASE / "models"
PAPER = BASE.parent / "paper.tex"


def write_paper_numbers():
    """Write every result shown in the manuscript from CSV artefacts.

    The manuscript consumes these macros/table bodies/plot coordinates rather
    than maintaining a second set of result values by hand.
    """
    def read(name):
        return pd.read_csv(MODELS / name, keep_default_na=False)
    def esc(value):
        return str(value).replace("_", "\\_").replace("%", "\\%")
    def f(value, digits=3):
        return f"{float(value):.{digits}f}"
    def pct(value, digits=1):
        return f"{100 * float(value):.{digits}f}"
    def macro(name, value):
        lines.append(f"\\newcommand{{\\{name}}}{{{value}\\xspace}}")
    def rawmacro(name, value):
        """A macro for a TeX list/body, where trailing inter-word space is wrong."""
        lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")
    def body(name, rows):
        lines.append(f"\\newcommand{{\\{name}}}{{%")
        lines.extend(rows)
        lines.append("}")
    def readable(feature):
        mapping = {"number_inpatient": "Num inpatient", "number_emergency": "Num emergency",
                   "number_diagnoses": "Num diagnoses", "time_in_hospital": "Time in Hospital",
                   "num_medications": "Num medications", "diabetesMed_Yes": "DiabetesMed",
                   "metformin_prescribed": "Metformin", "insulin_prescribed": "Insulin"}
        if feature in mapping: return mapping[feature]
        if feature.startswith("discharge_disposition_"):
            return "Discharge Disp.~" + feature.rsplit("_", 1)[1]
        if feature.startswith("diag_"):
            parts = feature.split("_")          # diag_1_group_Respiratory
            return f"Diag {parts[1]} {parts[-1].lower()}"
        return feature.replace("_", " ")
    excluded = ("discharge_disposition_", "time_in_hospital", "num_medications",
                "num_lab_procedures", "num_procedures", "number_diagnoses", "diag_")

    metrics = read("prediction_metrics.csv")
    held = metrics.loc[metrics.split.eq("held_out_test")].iloc[0]
    validation = metrics.loc[metrics.split.eq("validation")]
    shap = read("shap_global_importance.csv")
    perm = read("permutation_importance.csv")
    audit = read("causal_audit_full.csv")
    sensitivity = read("causal_audit_sensitivity_no_diag.csv")
    subgroup = read("heldout_subgroup_metrics.csv")
    di = read("disparate_impact.csv")
    simulation = read("simulation_validation.csv")
    robust = read("explainer_robustness.csv")
    semi = read("semisynthetic_validation.csv").iloc[0]
    feature_order = audit.feature.tolist()
    rank = {row.feature: i + 1 for i, row in shap.reset_index(drop=True).iterrows()}
    lines = ["% Auto-generated by run_btp_pipeline.py; do not edit by hand."]

    for key, value in {
        "HeldAUC": f(held.roc_auc), "HeldAUClo": f(held.roc_auc_ci_lower),
        "HeldAUChi": f(held.roc_auc_ci_upper), "HeldPRAUC": f(held.pr_auc),
        "HeldBrier": f(held.brier), "HeldPrecision": f(held.precision_at_0_5),
        "HeldRecall": f(held.recall_at_0_5), "HeldSlope": f(held.calibration_slope),
        "HeldIntercept": f(held.calibration_intercept), "TopThreshold": f(held.threshold_top20pct),
        "TopSensitivity": f(held.sensitivity_top20), "TopSpecificity": f(held.specificity_top20),
        "TopPPV": f(held.ppv_top20), "ZRank": str(int(semi.naive_model_shap_rank)),
        "ZMeanAbsSHAP": f(semi.naive_model_mean_abs_shap),
        "SemiRD": f(semi.rd, 4), "SemiCILo": f(semi.ci_lower, 4),
        "SemiCIHi": f(semi.ci_upper, 4), "SemiEValue": f(semi.e_value, 2),
        "SemiRetainedPct": pct(semi.overlap_fraction) + "\\%",
        "SemiCategory": str(semi.sensitivity_category),
    }.items(): macro(key, value)

    # Prose-level values.  Keeping these as macros makes a rerun the single
    # source of truth even where the same number appears in a table and prose.
    macro("TopPermImportance", f(perm.iloc[0].mean_auc_decrease))
    macro("TopPermFeature", esc(readable(perm.iloc[0].feature)))
    macro("AuditFeatureCount", str(len(audit)))
    macro("FragileCount", str(int(audit.sensitivity_category.eq("FRAGILE").sum())))
    macro("UncertainCount", str(int(audit.sensitivity_category.eq("UNCERTAIN").sum())))
    macro("RobustCount", str(int(audit.sensitivity_category.eq("ROBUST").sum())))
    for _, r in audit.iterrows():
        token = "".join(x.title() for x in str(r.feature).split("_"))
        macro(f"{token}RD", f(r.aipw_risk_difference))
        macro(f"{token}EValue", f(r.e_value_ci_bound, 2))
        macro(f"{token}Retained", pct(r.overlap_fraction))
        macro(f"{token}Q", f(r.bh_qvalue, 6))
    for label, part in simulation.groupby("exposure_type", sort=False):
        token = {"null": "SimNull", "delta_0.4": "SimModerate", "delta_1.0": "SimLarge"}[label]
        macro(f"{token}RD", f(part.true_rd.mean()))
        macro(f"{token}Coverage", f(part.ci_covers_truth.mean()))
    for _, r in robust.iterrows():
        token = (str(r.reference_method) + "_" + str(r.comparison_method)).replace("TreeSHAP_", "Tree").replace("_dependent", "Dep").replace("_interventional", "Inter").replace("KernelSHAP", "Kernel").replace("_", "")
        macro(f"Robust{token}Overlap", f"{int(r.top15_overlap_count)}/15")
        macro(f"Robust{token}Spearman", f(r.spearman_mean_abs_shap))

    # ---- Subgroup / DI / misc prose macros (single source of truth) --------
    def texbin(v): return str(v).replace("-", "--")
    age = subgroup.loc[subgroup.group.eq("age")].copy()
    age["auc"] = age.roc_auc.astype(float)
    age["lo"] = age.value.str.extract(r"\[(\d+)")[0].astype(int)
    age = age.sort_values("lo")
    amin, amax, young = age.loc[age.auc.idxmin()], age.loc[age.auc.idxmax()], age.iloc[0]
    macro("AgeAUCMin", f(amin.auc)); macro("AgeAUCMinGroup", texbin(amin.value))
    macro("AgeAUCMax", f(amax.auc)); macro("AgeAUCMaxGroup", texbin(amax.value))
    macro("YoungestGroup", texbin(young.value)); macro("YoungestAUC", f(young.auc))
    macro("YoungestN", str(int(young.n)))
    def sub(g, v): return subgroup.loc[subgroup.group.eq(g) & subgroup.value.eq(v)].iloc[0]
    other, male, female = sub("race", "Other"), sub("gender", "Male"), sub("gender", "Female")
    macro("OtherRaceAUC", f(other.roc_auc)); macro("OtherRaceN", str(int(other.n)))
    macro("OtherRacePrev", pct(other.prevalence) + "\\%")
    macro("MaleAUC", f(male.roc_auc)); macro("FemaleAUC", f(female.roc_auc))
    macro("TopSHAP", f(shap.iloc[0].mean_abs_shap))
    macro("ScreenedPatients", str(len(read("recourse_audit.csv"))))
    for _, r in audit.iterrows():
        token = "".join(x.title() for x in str(r.feature).split("_"))
        macro(f"{token}RetainedPct", pct(r.overlap_fraction) + "\\%")
    rev = di.loc[di.flag.eq("review")]
    if len(rev):
        listing = "; ".join(f"{esc(r.value)} (DI {f(r.disparate_impact_ratio,2)}, 95\\% CI [{f(r.di_ci_lower,2)}, {f(r.di_ci_upper,2)}], $n={int(sub(r.group, r.value).n)}$)" for _, r in rev.iterrows())
        macro("DIReviewSentence", f"Only {listing} {'is' if len(rev)==1 else 'are'} flagged for review (95\\% CI wholly outside [0.80, 1.25]); every other group whose CI crosses a band edge is inconclusive")
    else:
        macro("DIReviewSentence", "No group has a 95\\% CI wholly outside [0.80, 1.25]; every group whose CI crosses a band edge is inconclusive")
    body("GeneratedAgeAUCCoords", [f"({r.value},{f(r.auc)})" for _, r in age.iterrows()])
    body("GeneratedValidationRows", [
        f"{esc(r.model)} & {f(r.cv_auc_mean)} & {f(r.roc_auc)} & {f(r.pr_auc)} & {f(r.brier)} \\\\" for _, r in validation.iterrows()])
    body("GeneratedHeldoutRows", [
        "AUC-ROC & \\HeldAUC{} (95\\% CI: \\HeldAUClo--\\HeldAUChi) \\\\ ",
        "PR-AUC & \\HeldPRAUC \\\\ ", "Brier Score & \\HeldBrier \\\\ ",
        "Precision (at 0.5) & \\HeldPrecision \\\\ ", "Recall (at 0.5) & \\HeldRecall \\\\ ",
        "Calibration Slope & \\HeldSlope \\\\ ", "Calibration Intercept & \\HeldIntercept \\\\ ",
        "\\midrule", "\\multicolumn{2}{l}{\\textit{Top-20\\% operating point (threshold \\TopThreshold)}} \\\\ ",
        "Sensitivity & \\TopSensitivity \\\\ ", "Specificity & \\TopSpecificity \\\\ ", "PPV & \\TopPPV \\\\ "])
    body("GeneratedSHAPRows", [f"{i} & {esc(r.feature)}{'\\textsuperscript{\\textdagger}' if r.feature.startswith(excluded) else ''} & {f(r.mean_abs_shap,4)} \\\\" for i, (_, r) in enumerate(shap.head(12).iterrows(), 1)])
    body("GeneratedPermRows", [f"{esc(r.feature)} & {f(r.mean_auc_decrease,4)} \\\\" for _, r in perm.head(12).iterrows()])
    perm_plot = perm.head(12).iloc[::-1].reset_index(drop=True)
    perm_labels = [esc(readable(r.feature)) for _, r in perm_plot.iterrows()]
    perm_coords = [f"({f(r.mean_auc_decrease,4)},{i})" for i, (_, r) in enumerate(perm_plot.iterrows())]
    assert len(perm_labels) == len(perm_coords) == len(perm_plot)
    body("GeneratedPermCoords", perm_coords)
    rawmacro("GeneratedPermLabels", ",".join(perm_labels))
    body("GeneratedAuditRows", [
        f"{esc(r.feature)} & {rank[r.feature]} & {('Raises' if 'raises' in shap.loc[shap.feature.eq(r.feature),'shap_direction'].iloc[0] else 'Lowers')} & "
        f"${float(r.aipw_risk_difference):+.3f}$ & $[{float(r.rd_ci_lower):+.3f},{float(r.rd_ci_upper):+.3f}]$ & {f(r.aipw_risk_ratio,2)} & $[{f(r.rr_ci_lower,2)},{f(r.rr_ci_upper,2)}]$ & {f(r.e_value_ci_bound,2)} & {pct(r.overlap_fraction)} & {f(r.max_smd_post_weighting)} & {r.sensitivity_category} \\\\" for _, r in audit.iterrows()])
    evalue_plot = audit.iloc[::-1].reset_index(drop=True)
    evalue_labels = [esc(readable(r.feature)) for _, r in evalue_plot.iterrows()]
    evalue_coords = [f"({f(r.e_value_ci_bound,2)},{i})" for i, (_, r) in enumerate(evalue_plot.iterrows())]
    assert len(evalue_labels) == len(evalue_coords) == len(evalue_plot)
    body("GeneratedEValueCoords", evalue_coords)
    rawmacro("GeneratedEValueLabels", ",".join(evalue_labels))
    sens_by = sensitivity.set_index("feature")
    body("GeneratedSensitivityRows", [f"{esc(r.feature)} & ${float(r.aipw_risk_difference):+.3f}$ & {f(r.e_value_ci_bound,2)} & {r.sensitivity_category} & ${float(sens_by.loc[r.feature,'aipw_risk_difference']):+.3f}$ & {f(sens_by.loc[r.feature,'e_value_ci_bound'],2)} & {sens_by.loc[r.feature,'sensitivity_category']} \\\\" for _, r in audit.iterrows()])
    body("GeneratedSubgroupRows", [f"{esc(r.group)} & {esc(r.value)} & {int(r.n):,} & {pct(r.prevalence)}\\% & {f(r.roc_auc)} & {f(r.mean_predicted_risk)} \\\\" for _, r in subgroup.iterrows()])
    di_flag = {"within_0.80_1.25": "within", "review": "review", "inconclusive": "inconclusive", "reference": "reference"}
    body("GeneratedDIRows", [f"{esc(r.group)} & {esc(r.value)} & {int(subgroup.loc[(subgroup.group.eq(r.group)) & (subgroup.value.eq(r.value)),'n'].iloc[0]):,} & {f(r.disparate_impact_ratio,3)} & " + ("---" if r.di_ci_lower == "" else f"[{f(r.di_ci_lower,3)}, {f(r.di_ci_upper,3)}]") + f" & {di_flag.get(r.flag, esc(r.flag))} \\\\" for _, r in di.iterrows()])
    review = di.loc[di.flag.eq("review")]
    review_text = "; ".join(f"{r.value} ({f(r.disparate_impact_ratio,2)}, [{f(r.di_ci_lower,2)}, {f(r.di_ci_upper,2)}])" for _, r in review.iterrows()) or "none"
    macro("DIReviewGroups", review_text)
    sim_rows=[]
    for label, part in simulation.groupby("exposure_type", sort=False):
        counts=part.category.value_counts(); sim_rows.append(f"{esc(label)} & {f(part.true_rd.mean())} & {f(part.bias.mean(),4)} & {f(part.ci_covers_truth.mean())} & {int(counts.get('FRAGILE',0))}/{int(counts.get('UNCERTAIN',0))}/{int(counts.get('ROBUST',0))} \\\\")
    body("GeneratedSimulationRows", sim_rows)
    short = {"TreeSHAP_path_dependent": "TreeSHAP (path)", "TreeSHAP_interventional": "TreeSHAP (interv.)", "KernelSHAP": "KernelSHAP"}
    body("GeneratedRobustnessRows", [f"{short.get(r.reference_method, esc(r.reference_method))} vs. {short.get(r.comparison_method, esc(r.comparison_method))} & {int(r.top15_overlap_count)}/15 & {f(r.spearman_mean_abs_shap)} \\\\" for _, r in robust.iterrows()])
    generated = "\n".join(lines) + "\n"
    source = PAPER.read_text(encoding="utf-8")
    begin, end = "%%BEGIN_GENERATED", "%%END_GENERATED"
    if source.count(begin) != 1 or source.count(end) != 1:
        raise RuntimeError("paper.tex must contain exactly one generated marker pair")
    before, remainder = source.split(begin, 1)
    _, after = remainder.split(end, 1)
    PAPER.write_text(before + begin + "\n" + generated + end + after, encoding="utf-8")
    print(f"Embedded generated paper values in {PAPER}")
    # Strict leak check: ANY numeric literal outside the generated block that is
    # not an explicit design constant is a synchronisation error (this catches
    # stale values, not only values that currently equal a CSV entry).
    outside = before + after
    layout_words = ("definecolor", "minimum", "width", "height", "xmin", "xmax", "ymin", "ymax",
                    "arraystretch", "font=", "precision", "node distance", "Stealth", "enlarge",
                    "pgfplotsset", "inner sep", "rounded", "fill=", "extra x ticks", "\\bibitem", "p{")
    allowed = {"0.10", "0.90", "0.80", "1.25", "0.05", "1.05", "0.8", "0.7", "0.6", "0.3", "0.5", "0.4",
               "1.0", "2.0", "3.0", "3.11", "0.35", "0.85", "20\\%", "80\\%", "95\\%", "11\\%"}
    pattern = re.compile(r"(?<![\w.\\])[+\-]?\d+\.\d+(?!\s*(?:cm|pt|mm|em))|\b\d+(?:\.\d+)?\\%|\bn\s*=\s*\d+|\bn=\d+")
    hits = []
    for number, line in enumerate(outside.splitlines(), 1):
        if line.lstrip().startswith("%") or any(w in line for w in layout_words):
            continue
        for match in pattern.finditer(line):
            token = match.group(0).lstrip("+-")
            if token in allowed or token.startswith("-0.90"):
                continue
            hits.append(f"line {number}: {match.group(0)}  | {line.strip()[:80]}")
    print("Paper result-literal leak check: " + ("PASS" if not hits else f"FAIL ({len(hits)})\n  " + "\n  ".join(hits)))
    if hits:
        raise RuntimeError("result literals remain outside the generated block")


def run_all():
    import aux_fairness, data_preprocessing, layer1, layer1_shap, layer2_causal
    import layer3_counterfactual, layer_baseline_comparison, layer_semisynthetic
    data_preprocessing.run()
    layer1.train()
    layer1_shap.run()
    causal  = layer2_causal.run()
    fairness = aux_fairness.run()
    recourse = layer3_counterfactual.run()
    baseline = layer_baseline_comparison.run()
    validation = layer_semisynthetic.run()
    write_paper_numbers()
    print("\nCompleted. Results are in codebase/models/.")
    return causal, fairness, recourse


if __name__ == "__main__":
    run_all()
